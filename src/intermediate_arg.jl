const INT_SQRT_PID2 = 1.2533141373155003

# Clenshaw in the Chebyshev basis for W coefficient columns at once.
# (`map` over the tuples, not a closure over b1/b2: closures capturing variables that a
# loop reassigns get boxed in Julia.)
# `c[k]` is the W-tuple of row k (k = 1 is the lowest degree).
@inline function ycl(t, c::NTuple{R,NTuple{W,T}}) where {R,W,T}
    t2 = t + t
    b1 = ntuple(_ -> 0.0, Val(W))
    b2 = b1
    @inbounds for k in R:-1:2
        ck = c[k]
        bk = map((c_, p, q) -> muladd(t2, p, c_ - q), ck, b1, b2)
        b2 = b1
        b1 = bk
    end
    c1 = @inbounds c[1]
    return map((c_, p, q) -> muladd(t, p, c_ - q), c1, b1, b2)
end

# `idx` is 1-based (1:4).
@inline function eval_tab(idx::Int, z, a, b)
    sz = @inbounds (z - INT_ZMID[idx]) * INT_ZHALFINV[idx]
    g0 = @inbounds ycl(sz, INT_G0[idx])
    g1 = @inbounds ycl(sz, INT_G1[idx])
    g2 = @inbounds ycl(sz, INT_G2[idx])
    col = (g0..., g1..., g2...) # 9 coefficients in u

    # u-Clenshaw for both orders in two lanes. su = 2u/U_HI - 1
    k = 2.0 / 1.0100249999999997
    su = ((a * a) * k - 1.0, (b * b) * k - 1.0)
    su2 = (su[1] + su[1], su[2] + su[2])
    b1 = (0.0, 0.0)
    b2 = (0.0, 0.0)
    @inbounds for j in 9:-1:2
        cj = col[j]
        bk = (muladd(su2[1], b1[1], cj - b2[1]), muladd(su2[2], b1[2], cj - b2[2]))
        b2 = b1
        b1 = bk
    end
    s = z * INT_SQRT_PID2
    c1 = col[1]
    return (s * muladd(su[1], b1[1], c1 - b2[1]),
            s * muladd(su[2], b1[2], c1 - b2[2]))
end

# Branch-free table index in 1:4.
@inline table_index(z) =
    1 + (z > INT_ZBREAK[1]) + (z > INT_ZBREAK[2]) + (z > INT_ZBREAK[3])

@inline function _besselkx_intermediate_pair(a, b, x)
    z = 1.0 / sqrt(x)
    return eval_tab(table_index(z), z, a, b)
end

# e^x K_a(x) and e^x K_{a-1}(x)
@inline function besselkx_intermediate_pair(a, x)
    b = a < 1.0 ? 1.0 - a : a - 1.0
    return _besselkx_intermediate_pair(a, b, x)
end

# K_a(x) and K_{a-1}(x)
@inline function besselk_intermediate_pair(a, x)
    kx_a, kx_am1 = besselkx_intermediate_pair(a, x)
    e = exp(-x)
    return (kx_a * e, kx_am1 * e)
end
